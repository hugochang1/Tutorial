// CUDA 核心函數：3D 矩陣相加
__global__ void matrixAdd3D(const float* A, const float* B, float* C, int width, int height, int depth) {
    // 計算當前執行緒在 3D 網格中的全域座標 (x, y, z)
    int x = blockIdx.x * blockDim.x + threadIdx.x; // 對應 Width (行 Col)
    int y = blockIdx.y * blockDim.y + threadIdx.y; // 對應 Height (列 Row)
    int z = blockIdx.z * blockDim.z + threadIdx.z; // 對應 Depth (層 Slice)

    printf("[Block(%d,%d,%d)][Thread(%d,%d,%d)] -> Global(X:%d, Y:%d, Z:%d)\n",
        blockIdx.x, blockIdx.y, blockIdx.z,
        threadIdx.x, threadIdx.y, threadIdx.z,
        x, y, z);

    // 確保索引沒有超出 3D 矩陣邊界
    if (x < width && y < height && z < depth) {
        // 將 3D 座標轉換為 1D 線性記憶體索引
        // 矩陣儲存順序通常為：Row-major（Z * Height * Width + Y * Width + X）
        int idx = z * (height * width) + y * width + x;
        C[idx] = A[idx] + B[idx];
    }
}

int main() {
    // 定義 3D 矩陣維度 (128 x 128 * 64 = 1,048,576 個元素)
    const int WIDTH = 8; // X 軸
    const int HEIGHT = 8; // Y 軸
    const int DEPTH = 8;  // Z 軸

    const int SIZE = WIDTH * HEIGHT * DEPTH;
    const size_t bytes = SIZE * sizeof(float);

    // 1. 配置主機端（CPU）記憶體並初始化
    float* h_A = (float*)malloc(bytes);
    float* h_B = (float*)malloc(bytes);
    float* h_C = (float*)malloc(bytes);

    for (int i = 0; i < SIZE; ++i) {
        h_A[i] = 1.5f;
        h_B[i] = 2.5f;
    }

    // 2. 配置裝置端（GPU）記憶體
    float* d_A, * d_B, * d_C;
    cudaMalloc(&d_A, bytes);
    cudaMalloc(&d_B, bytes);
    cudaMalloc(&d_C, bytes);

    // 3. 資料從 CPU 複製到 GPU
    cudaMemcpy(d_A, h_A, bytes, cudaMemcpyHostToDevice);
    cudaMemcpy(d_B, h_B, bytes, cudaMemcpyHostToDevice);

    // 4. 定義 3D 區塊（Block）與網格（Grid）大小
    // 注意：每個 Block 的執行緒總數 (X*Y*Z) 在多數主流 GPU 上不能超過 1024
    // 這裡配置 8 * 8 * 8 = 512 個執行緒，符合限制
    dim3 threadsPerBlock(8, 8, 8);

    // 計算所需 3D Grid 大小，確保覆蓋整個 3D 空間
    dim3 numBlocks((WIDTH + threadsPerBlock.x - 1) / threadsPerBlock.x,
        (HEIGHT + threadsPerBlock.y - 1) / threadsPerBlock.y,
        (DEPTH + threadsPerBlock.z - 1) / threadsPerBlock.z);

    std::cout << "啟動 3D Kernel..." << std::endl;
    std::cout << "Grid 大小: (" << numBlocks.x << ", " << numBlocks.y << ", " << numBlocks.z << ")" << std::endl;
    std::cout << "Block 大小: (" << threadsPerBlock.x << ", " << threadsPerBlock.y << ", " << threadsPerBlock.z << ")\n" << std::endl;

    // 5. 調用 3D 核心函數
    matrixAdd3D << <numBlocks, threadsPerBlock >> > (d_A, d_B, d_C, WIDTH, HEIGHT, DEPTH);

    // 同步裝置以確保 GPU printf 輸出完畢
    cudaDeviceSynchronize();

    // 檢查錯誤
    cudaError_t err = cudaGetLastError();
    if (err != cudaSuccess) {
        std::cerr << "CUDA Error: " << cudaGetErrorString(err) << std::endl;
        return -1;
    }

    // 6. 結果從 GPU 複製回 CPU
    cudaMemcpy(h_C, d_C, bytes, cudaMemcpyDeviceToHost);

    // 7. 驗證結果
    bool success = true;
    for (int i = 0; i < SIZE; ++i) {
        if (fabs(h_C[i] - 4.0f) > 1e-5) {
            success = false;
            break;
        }
    }

    if (success) {
        std::cout << "\n3D 矩陣相加成功！結果正確。" << std::endl;
    }
    else {
        std::cout << "\n結果錯誤！" << std::endl;
    }

    // 8. 釋放記憶體
    cudaFree(d_A); cudaFree(d_B); cudaFree(d_C);
    free(h_A); free(h_B); free(h_C);

    return 0;
}
